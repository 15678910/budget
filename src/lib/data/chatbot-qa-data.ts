// ─── 키워드 매칭 엔진 ───

/**
 * 사용자 질문을 키워드 매칭으로 Q&A 쌍에서 검색
 * @returns 매칭된 QAPair 또는 null (API 폴백 필요)
 */
export function findBestMatch(departmentId: DepartmentId, userQuestion: string): QAPair | null {
  const qaPairs = DEPARTMENT_QA_MAP[departmentId];
  if (!qaPairs) return null;

  const normalizedQ = userQuestion.toLowerCase().replace(/\s+/g, '');

  let bestScore = 0;
  let bestMatch: QAPair | null = null;

  for (const pair of qaPairs) {
    let score = 0;
    for (const keyword of pair.keywords) {
      if (normalizedQ.includes(keyword)) {
        score += 1;
      }
    }
    // 최소 1개 키워드 매칭 필요, 더 많이 매칭될수록 높은 점수
    if (score > bestScore) {
      bestScore = score;
      bestMatch = pair;
    }
  }

  return bestMatch;
}
