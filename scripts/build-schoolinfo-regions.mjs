const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function sggName(sido, sgg) {
  // 학교현황(62) → ADRCD_NM "서울특별시 종로구" 의 시군구 부분. 초중고 순으로 시도
  for (const knd of ['02', '03', '04']) {
    try {
      const url = `${BASE}?apiKey=${KEY}&apiType=62&pbanYr=2024&schulKndCode=${knd}&sidoCode=${sido}&sggCode=${sgg}`;
      const res = await fetch(url);
      if (!res.ok) continue;
      const j = await res.json();
      const nm = j?.list?.[0]?.ADRCD_NM;
      if (nm) {
        const parts = nm.trim().split(/\s+/);
        return parts.slice(1).join(' ') || nm; // 시도 뒤 = 시군구
      }
    } catch { /* skip */ }
  }
  return null;
}

(async () => {
  const out = {};
  for (const sido of Object.keys(REGIONS)) {
    out[sido] = { name: SIDO_NM[sido], sgg: [] };
    for (const sgg of REGIONS[sido]) {
      const nm = await sggName(sido, sgg);
      if (nm) out[sido].sgg.push({ code: sgg, name: nm });
      process.stderr.write(`\r${SIDO_NM[sido]} ${sgg} ${nm || '(無)'}            `);
      await sleep(150);
    }
  }
  process.stderr.write('\n');

  const sidos = Object.entries(out).map(([code, v]) => ({ code, name: v.name, sgg: v.sgg }));
  const ts = `// 학교알리미 시도/시군구 코드↔명칭 — 자동생성 (scripts/build-schoolinfo-regions.mjs)
// 셀프조회 셀렉트용. 수동 편집 금지.
export interface SggOption { code: string; name: string }
export interface SidoOption { code: string; name: string; sgg: SggOption[] }
export const SCHOOLINFO_REGIONS: SidoOption[] = ${JSON.stringify(sidos, null, 1)};
`;
  writeFileSync('src/lib/data/schoolinfo-regions.ts', ts);
  const total = sidos.reduce((s, x) => s + x.sgg.length, 0);
  console.log(`✅ src/lib/data/schoolinfo-regions.ts — 시도 ${sidos.length}, 시군구 ${total}`);
})();
